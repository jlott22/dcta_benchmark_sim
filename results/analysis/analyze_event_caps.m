% analyze_event_caps.m
% Audit scheduler-event safety caps and successful-trial headroom across all
% active DCTA core and sensitivity result bundles.
%
% The user-requested conservative reference is the lower historical cap of
% 5,000 scheduler events. Actual recorded caps are never overwritten: their
% minimum and maximum are retained separately. For known-target (CV) files,
% events_processed permits exact cap/event ratios. CLIPS and FGS do not store
% successful event counts, so cap/step ratios are labeled as upper-bound
% headroom proxies, not event-count estimates.

clear; clc;

scriptDir = fileparts(mfilename('fullpath'));
repoRoot = fileparts(fileparts(scriptDir));
tableDir = fullfile(scriptDir, 'tables');
if ~exist(tableDir, 'dir'), mkdir(tableDir); end

logFile = fullfile(tableDir, 'event_cap_analysis_log.txt');
if isfile(logFile), delete(logFile); end
diary(logFile);
cleanupDiary = onCleanup(@() diary('off'));

LOWER_HISTORICAL_CAP = 5000;
STAGNATION_LIMIT = 2000;

specs = makeSpecs(repoRoot);
groupParts = cell(1, numel(specs));
campaignParts = cell(1, numel(specs));
failureParts = cell(1, numel(specs));
manifestRows = cell(1, numel(specs));

fprintf('DCTA event-cap audit\n');
fprintf('Started: %s\n', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss Z')));
fprintf('Conservative comparison cap: %d scheduler events\n\n', LOWER_HISTORICAL_CAP);

for si = 1:numel(specs)
    spec = specs(si);
    if ~isfile(spec.file)
        error('Required active result file is absent: %s', spec.file);
    end
    info = dir(spec.file);
    prefix = string(repoRoot) + filesep;
    sourcePath = string(spec.file);
    assert(startsWith(lower(sourcePath), lower(prefix)), ...
        'Source path is outside the repository: %s', sourcePath);
    repositoryPath = replace(extractAfter(sourcePath, strlength(prefix)), '\', '/');
    manifestRows{si} = table(string(spec.campaign), string(spec.mission), ...
        repositoryPath, info.bytes, ...
        string(datetime(info.datenum, 'ConvertFrom', 'datenum', ...
        'Format', 'yyyy-MM-dd HH:mm:ss Z')), ...
        'VariableNames', {'campaign', 'mission', 'path', 'bytes', 'last_modified'});

    opts = detectImportOptions(spec.file, 'TextType', 'string');
    textVars = intersect({'trial_status', 'failure_message'}, ...
        opts.VariableNames, 'stable');
    opts = setvartype(opts, textVars, 'string');
    T = readtable(spec.file, opts);
    T = normalizeTable(T, spec);
    groupParts{si} = summarizeGridRobot(T, spec, LOWER_HISTORICAL_CAP);
    campaignParts{si} = summarizeCampaign(T, spec, LOWER_HISTORICAL_CAP);
    failureParts{si} = summarizeFailures(T, spec, LOWER_HISTORICAL_CAP, STAGNATION_LIMIT);

    fprintf('%s: attempted=%d successful=%d failed=%d\n', spec.campaign, ...
        height(T), sum(T.success), sum(~T.success));
end

groupSummary = vertcat(groupParts{:});
campaignSummary = vertcat(campaignParts{:});
failureSummary = vertcat(failureParts{:});
sourceManifest = vertcat(manifestRows{:});
adaptiveSchedule = makeAdaptiveSchedule(groupSummary);

writetable(sourceManifest, fullfile(tableDir, 'event_cap_source_manifest.csv'));
writetable(campaignSummary, fullfile(tableDir, 'event_cap_campaign_summary.csv'));
writetable(groupSummary, fullfile(tableDir, 'event_cap_grid_robot_summary.csv'));
writetable(failureSummary, fullfile(tableDir, 'event_cap_failure_breakdown.csv'));
writetable(adaptiveSchedule, fullfile(tableDir, 'event_cap_adaptive_schedule.csv'));

reportFile = fullfile(scriptDir, 'EVENT_CAP_ANALYSIS.md');
writeReport(reportFile, campaignSummary, groupSummary, failureSummary, ...
    adaptiveSchedule, LOWER_HISTORICAL_CAP, STAGNATION_LIMIT);

validateResults(specs, campaignSummary, groupSummary, failureSummary, ...
    adaptiveSchedule, LOWER_HISTORICAL_CAP);

fprintf('\nPASS: cap audit completed.\n');
fprintf('Report: results/analysis/EVENT_CAP_ANALYSIS.md\n');
fprintf('Tables: results/analysis/tables\n');

