function T = normalizeTable(T, spec)
    required = ["trial_status", "grid_size", "robot_count", "total_team_steps", ...
        string(spec.maxColumn)];
    missing = setdiff(required, string(T.Properties.VariableNames));
    if ~isempty(missing)
        error('%s lacks required columns: %s', spec.campaign, strjoin(cellstr(missing), ', '));
    end
    T.grid_size_numeric = asDouble(T.grid_size);
    T.robot_count_numeric = asDouble(T.robot_count);
    T.total_team_steps_numeric = asDouble(T.total_team_steps);
    T.max_agent_steps_numeric = asDouble(T.(spec.maxColumn));
    T.success = lower(string(T.trial_status)) ~= "failed";
    if ismember('debug_max_events', T.Properties.VariableNames)
        T.recorded_cap = asDouble(T.debug_max_events);
    else
        T.recorded_cap = nan(height(T), 1);
    end
    if ismember('events_processed', T.Properties.VariableNames)
        T.events_processed_numeric = asDouble(T.events_processed);
    else
        T.events_processed_numeric = nan(height(T), 1);
    end
    if ismember('failure_message', T.Properties.VariableNames)
        % Some combined CSVs retain a leading space before the exception
        % text. Normalize it before classifying the failure mechanism.
        T.failure_message_text = strtrim(string(T.failure_message));
    else
        T.failure_message_text = strings(height(T), 1);
    end
end

function summary = summarizeGridRobot(T, spec, lowerCap)
    [g, grids, robots] = findgroups(T.grid_size_numeric, T.robot_count_numeric);
    rows = cell(max(g), 1);
    for gi = 1:max(g)
        G = T(g == gi, :);
        S = G(G.success, :);
        steps = S.total_team_steps_numeric(isfinite(S.total_team_steps_numeric));
        maxSteps = S.max_agent_steps_numeric(isfinite(S.max_agent_steps_numeric));
        events = S.events_processed_numeric(isfinite(S.events_processed_numeric));
        caps = G.recorded_cap(isfinite(G.recorded_cap) & G.recorded_cap > 0);
        capHits = ~G.success & contains(G.failure_message_text, "Debug safety cap reached");
        stagnantHits = ~G.success & contains(G.failure_message_text, "Stagnation detected");
        recordedMin = finiteMin(caps); recordedMax = finiteMax(caps);
        [stepMean, stepMedian, stepP95, stepMax] = distributionStats(steps);
        [maxStepMean, ~, maxStepP95, maxStepMax] = distributionStats(maxSteps);
        [eventMean, eventMedian, eventP95, eventMax] = distributionStats(events);
        validEventRatio = isfinite(S.events_processed_numeric) & ...
            isfinite(S.total_team_steps_numeric) & S.total_team_steps_numeric > 0;
        eventPerStep = safeRatio(S.events_processed_numeric(validEventRatio), ...
            S.total_team_steps_numeric(validEventRatio));
        rows{gi} = table(string(spec.campaign), string(spec.mission), ...
            string(spec.family), grids(gi), robots(gi), grids(gi)^2, ...
            adaptiveCap(grids(gi), robots(gi)), lowerCap, recordedMin, ...
            recordedMax, height(G), height(S), height(G) - height(S), ...
            sum(capHits), sum(stagnantHits), numel(steps), stepMean, ...
            stepMedian, stepP95, stepMax, maxStepMean, maxStepP95, ...
            maxStepMax, ratio(lowerCap, stepMean), ratio(lowerCap, stepP95), ...
            ratio(lowerCap, stepMax), numel(events), eventMean, eventMedian, ...
            eventP95, eventMax, ratio(lowerCap, eventMean), ...
            ratio(lowerCap, eventP95), ratio(lowerCap, eventMax), ...
            mean(eventPerStep, 'omitnan'), ...
            proxyLabel(spec.mission, numel(events)), ...
            'VariableNames', {'campaign', 'mission', 'campaign_family', ...
            'grid_size', 'robot_count', 'grid_cells', 'default_adaptive_cap', ...
            'conservative_lower_cap', 'recorded_cap_min', 'recorded_cap_max', ...
            'attempted_n', 'successful_n', 'failed_n', 'event_cap_failure_n', ...
            'stagnation_failure_n', 'successful_step_n', ...
            'mean_success_total_team_steps', 'median_success_total_team_steps', ...
            'p95_success_total_team_steps', 'max_success_total_team_steps', ...
            'mean_success_max_agent_steps', 'p95_success_max_agent_steps', ...
            'max_success_max_agent_steps', 'lower_cap_over_mean_team_steps', ...
            'lower_cap_over_p95_team_steps', 'lower_cap_over_max_team_steps', ...
            'successful_exact_event_n', 'mean_success_events_processed', ...
            'median_success_events_processed', 'p95_success_events_processed', ...
            'max_success_events_processed', 'lower_cap_over_mean_success_events', ...
            'lower_cap_over_p95_success_events', 'lower_cap_over_max_success_events', ...
            'mean_events_per_team_step', 'interpretation'});
    end
    summary = vertcat(rows{:});
end

function summary = summarizeCampaign(T, spec, lowerCap)
    S = T(T.success, :);
    steps = S.total_team_steps_numeric(isfinite(S.total_team_steps_numeric));
    maxSteps = S.max_agent_steps_numeric(isfinite(S.max_agent_steps_numeric));
    events = S.events_processed_numeric(isfinite(S.events_processed_numeric));
    caps = T.recorded_cap(isfinite(T.recorded_cap) & T.recorded_cap > 0);
    [stepMean, stepMedian, stepP95, stepMax] = distributionStats(steps);
    [maxStepMean, ~, maxStepP95, maxStepMax] = distributionStats(maxSteps);
    [eventMean, eventMedian, eventP95, eventMax] = distributionStats(events);
    validEventRatio = isfinite(S.events_processed_numeric) & isfinite(S.total_team_steps_numeric) & S.total_team_steps_numeric > 0;
    eventPerStep = safeRatio(S.events_processed_numeric(validEventRatio), S.total_team_steps_numeric(validEventRatio));
    eventCaps = ~T.success & contains(T.failure_message_text, "Debug safety cap reached");
    stagnation = ~T.success & contains(T.failure_message_text, "Stagnation detected");
    unrecovered = ~T.success & contains(T.failure_message_text, "No result rows were recovered");
    other = ~T.success & ~eventCaps & ~stagnation & ~unrecovered;
    summary = table(string(spec.campaign), string(spec.mission), ...
        string(spec.family), height(T), height(S), height(T) - height(S), ...
        sum(eventCaps), sum(stagnation), sum(unrecovered), sum(other), ...
        lowerCap, finiteMin(caps), finiteMax(caps), numel(steps), ...
        stepMean, stepMedian, stepP95, stepMax, maxStepMean, maxStepP95, ...
        maxStepMax, ratio(lowerCap, stepMean), ratio(lowerCap, stepP95), ...
        ratio(lowerCap, stepMax), numel(events), eventMean, eventMedian, ...
        eventP95, eventMax, ratio(lowerCap, eventMean), ...
        ratio(lowerCap, eventP95), ratio(lowerCap, eventMax), ...
        mean(eventPerStep, 'omitnan'), proxyLabel(spec.mission, numel(events)), ...
        'VariableNames', {'campaign', 'mission', 'campaign_family', ...
        'attempted_n', 'successful_n', 'failed_n', 'event_cap_failure_n', ...
        'stagnation_failure_n', 'unrecovered_output_n', 'other_failure_n', ...
        'conservative_lower_cap', 'recorded_cap_min', 'recorded_cap_max', ...
        'successful_step_n', 'mean_success_total_team_steps', ...
        'median_success_total_team_steps', 'p95_success_total_team_steps', ...
        'max_success_total_team_steps', 'mean_success_max_agent_steps', ...
        'p95_success_max_agent_steps', 'max_success_max_agent_steps', ...
        'lower_cap_over_mean_team_steps', 'lower_cap_over_p95_team_steps', ...
        'lower_cap_over_max_team_steps', 'successful_exact_event_n', ...
        'mean_success_events_processed', 'median_success_events_processed', ...
        'p95_success_events_processed', 'max_success_events_processed', ...
        'lower_cap_over_mean_success_events', 'lower_cap_over_p95_success_events', ...
        'lower_cap_over_max_success_events', 'mean_events_per_team_step', ...
        'interpretation'});
end

function summary = summarizeFailures(T, spec, lowerCap, stagnationLimit)
    F = T(~T.success, :);
    eventCap = contains(F.failure_message_text, "Debug safety cap reached");
    stagnation = contains(F.failure_message_text, "Stagnation detected");
    unrecovered = contains(F.failure_message_text, "No result rows were recovered");
    other = ~eventCap & ~stagnation & ~unrecovered;
    capValues = F.recorded_cap(eventCap & isfinite(F.recorded_cap));
    stagnationEvents = extractDiagnosticEvents(F.failure_message_text(stagnation));
    summary = table(string(spec.campaign), string(spec.mission), ...
        string(spec.family), height(F), sum(eventCap), sum(stagnation), ...
        sum(unrecovered), sum(other), sum(eventCap & F.recorded_cap == lowerCap), ...
        sum(eventCap & F.recorded_cap > lowerCap), finiteMin(capValues), ...
        finiteMax(capValues), stagnationLimit, finiteMin(stagnationEvents), ...
        finiteMax(stagnationEvents), ...
        'VariableNames', {'campaign', 'mission', 'campaign_family', ...
        'failed_n', 'event_cap_failure_n', 'stagnation_failure_n', ...
        'unrecovered_output_n', 'other_failure_n', ...
        'event_cap_failures_at_lower_5000_n', ...
        'event_cap_failures_above_lower_5000_n', ...
        'event_cap_failure_recorded_cap_min', ...
        'event_cap_failure_recorded_cap_max', ...
        'stagnation_consecutive_no_progress_limit', ...
        'stagnation_total_events_min', 'stagnation_total_events_max'});
end

function schedule = makeAdaptiveSchedule(groupSummary)
    G = unique(groupSummary(:, {'grid_size', 'robot_count', 'grid_cells', ...
        'default_adaptive_cap', 'conservative_lower_cap'}));
    G = sortrows(G, {'grid_size', 'robot_count'});
    G.adaptive_over_lower = G.default_adaptive_cap ./ G.conservative_lower_cap;
    G.formula = repmat("max(5000, ceil(10000*grid_size^2*robot_count/(19^2*4)))", height(G), 1);
    schedule = G;
end

function writeReport(path, campaigns, groups, failures, schedule, lowerCap, stagnationLimit)
    fid = fopen(path, 'w');
    if fid < 0, error('Could not create report: %s', path); end
    cleanup = onCleanup(@() fclose(fid));

    fprintf(fid, '# Scheduler-event cap and stagnation analysis\n\n');
    fprintf(fid, 'Generated by `results/analysis/analyze_event_caps.m` from all active core and sensitivity system-performance tables.\n\n');
    fprintf(fid, '## What the two limits mean\n\n');
    fprintf(fid, ['The global event cap counts scheduler activations. Each activation calls one robot once and may produce movement, turning, intent synchronization, replanning, idling, or a no-goal response. ', ...
        'It is therefore not a step limit or a wall-clock timeout. The scheduler checks mission completion before applying the cap; a cap exception means the mission was still incomplete at that event count.\n\n']);
    fprintf(fid, ['The known-target simulator also applies a stagnation detector at %d consecutive scheduler events with no change in either robot positions or the number of completed targets. ', ...
        'The counter resets whenever a robot moves or a target is completed. This detector is checked before the global event cap, so it can terminate a no-progress run earlier; total events at termination can exceed %d because the threshold concerns only the current consecutive no-progress streak.\n\n'], ...
        stagnationLimit, stagnationLimit);
    fprintf(fid, ['Because settings changed during the campaigns, the tables preserve recorded cap minima and maxima. At the user''s request, all cross-campaign headroom comparisons use the lower historical reference of %d events. ', ...
        'That conservative reference does not claim every stored run was actually configured at %d.\n\n'], lowerCap, lowerCap);
    fprintf(fid, ['The grid/robot schedule below is the present configuration default, not a reconstruction of every historical run. It can be overridden by a worker or command-line setting; notably, the current known-target grid-density worker sets 800,000 events explicitly. ', ...
        'In the uploaded known-target grid data, failed rows record 5,000 while successful rows omit the cap, and some successful trials processed more than 5,000 events. Therefore the default-schedule multiples are scenario context, whereas only populated recorded-cap fields establish historical settings.\n\n']);

    fprintf(fid, '## Campaign-level successful-trial scale\n\n');
    fprintf(fid, '| Campaign | Success/attempted | Cap failures | Stagnation | Recorded cap range | Mean / p95 / max team steps | 5000 / mean steps | Exact mean events | 5000 / mean events |\n');
    fprintf(fid, '|---|---:|---:|---:|---:|---:|---:|---:|---:|\n');
    for i = 1:height(campaigns)
        fprintf(fid, '| %s | %d/%d | %d | %d | %s | %.1f / %.1f / %.0f | %.2fx | %s | %s |\n', ...
            char(campaigns.campaign(i)), campaigns.successful_n(i), campaigns.attempted_n(i), ...
            campaigns.event_cap_failure_n(i), campaigns.stagnation_failure_n(i), ...
            rangeText(campaigns.recorded_cap_min(i), campaigns.recorded_cap_max(i)), ...
            campaigns.mean_success_total_team_steps(i), campaigns.p95_success_total_team_steps(i), ...
            campaigns.max_success_total_team_steps(i), campaigns.lower_cap_over_mean_team_steps(i), ...
            numberOrNA(campaigns.mean_success_events_processed(i), '%.1f'), ...
            multipleOrNA(campaigns.lower_cap_over_mean_success_events(i)));
    end
    fprintf(fid, '\nFor CLIPS and FGS, `5000 / mean steps` is only a step-based upper-bound proxy: nonmovement scheduler events are not represented in the exported step totals. For CV, exact `events_processed` makes the event ratio direct.\n\n');

    fprintf(fid, '## Grid-density levels\n\n');
    for mission = ["CLIPS", "CV", "FGS"]
        G = groups(groups.campaign == mission + " grid-density", :);
        fprintf(fid, '### %s\n\n', mission);
        fprintf(fid, '| Grid | Robots | Default adaptive cap | Recorded cap range | Success/attempted | Mean / p95 / max team steps | 5000 / mean steps | Default / mean steps | Mean events | 5000 / mean events | Default / mean events |\n');
        fprintf(fid, '|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n');
        for i = 1:height(G)
            fprintf(fid, '| %d | %d | %d | %s | %d/%d | %.1f / %.1f / %.0f | %.2fx | %.2fx | %s | %s | %s |\n', ...
                G.grid_size(i), G.robot_count(i), G.default_adaptive_cap(i), ...
                rangeText(G.recorded_cap_min(i), G.recorded_cap_max(i)), ...
                G.successful_n(i), G.attempted_n(i), ...
                G.mean_success_total_team_steps(i), G.p95_success_total_team_steps(i), ...
                G.max_success_total_team_steps(i), G.lower_cap_over_mean_team_steps(i), ...
                ratio(G.default_adaptive_cap(i), G.mean_success_total_team_steps(i)), ...
                numberOrNA(G.mean_success_events_processed(i), '%.1f'), ...
                multipleOrNA(G.lower_cap_over_mean_success_events(i)), ...
                multipleOrNA(ratio(G.default_adaptive_cap(i), G.mean_success_events_processed(i))));
        end
        fprintf(fid, '\n');
    end

    fprintf(fid, '## Default adaptive cap schedule for observed grid/robot combinations\n\n');
    fprintf(fid, 'The current formula is `max(5000, ceil(10000*grid_size^2*robot_count/(19^2*4)))`.\n\n');
    fprintf(fid, '| Grid | Robots | Lower reference | Default adaptive cap | Adaptive/lower |\n');
    fprintf(fid, '|---:|---:|---:|---:|---:|\n');
    for i = 1:height(schedule)
        fprintf(fid, '| %d | %d | %d | %d | %.2fx |\n', schedule.grid_size(i), ...
            schedule.robot_count(i), schedule.conservative_lower_cap(i), ...
            schedule.default_adaptive_cap(i), schedule.adaptive_over_lower(i));
    end
    fprintf(fid, '\n');

    fprintf(fid, '## Failure classification\n\n');
    fprintf(fid, '| Campaign | Failed | Event cap | At 5000 | Above 5000 | Stagnation | Unrecovered | Other |\n');
    fprintf(fid, '|---|---:|---:|---:|---:|---:|---:|---:|\n');
    for i = 1:height(failures)
        fprintf(fid, '| %s | %d | %d | %d | %d | %d | %d | %d |\n', ...
            char(failures.campaign(i)), failures.failed_n(i), ...
            failures.event_cap_failure_n(i), ...
            failures.event_cap_failures_at_lower_5000_n(i), ...
            failures.event_cap_failures_above_lower_5000_n(i), ...
            failures.stagnation_failure_n(i), failures.unrecovered_output_n(i), ...
            failures.other_failure_n(i));
    end
    fprintf(fid, '\nIn the CV grid-density campaign, the stagnation failures occurred after %d consecutive no-progress events at total event counts from %.0f to %.0f, all before the 5,000-event global cap.\n\n', ...
        stagnationLimit, finiteMin(failures.stagnation_total_events_min), ...
        finiteMax(failures.stagnation_total_events_max));

    fprintf(fid, '## Paper-ready context\n\n');
    fprintf(fid, ['"Trials were protected by a scheduler-event safety limit rather than a mission-time cutoff. Scheduler events include both movement and nonmovement activations, so the limit is not directly comparable to path steps. ', ...
        'Because cap settings changed, we use 5,000 events as a conservative common reference and separately report populated per-run cap fields; the present adaptive default is shown only as scenario context. Successful-trial step totals and, where exported for Collaborative Visit, exact event counts provide context for the available headroom but do not redefine the cap. ', ...
        'The known-target simulator additionally stopped runs after 2,000 consecutive events with neither robot movement nor target completion, resetting the counter whenever progress occurred. ', ...
        'Runs reaching either safeguard before mission completion were classified as noncompletions and were not assigned artificial step penalties."\n\n']);
    fprintf(fid, 'Exact values and all caveats are in `results/analysis/tables/event_cap_*.csv`.\n');
end

function validateResults(specs, campaigns, groups, failures, schedule, lowerCap)
    assert(height(campaigns) == numel(specs));
    assert(all(campaigns.attempted_n == campaigns.successful_n + campaigns.failed_n));
    assert(all(failures.failed_n == failures.event_cap_failure_n + ...
        failures.stagnation_failure_n + failures.unrecovered_output_n + failures.other_failure_n));
    assert(all(groups.attempted_n == groups.successful_n + groups.failed_n));
    assert(all(groups.conservative_lower_cap == lowerCap));
    assert(all(schedule.default_adaptive_cap >= lowerCap));
    assert(sum(campaigns.attempted_n) == 279600);
    assert(sum(campaigns.successful_n) == 277445);
    assert(sum(campaigns.failed_n) == 2155);
    assert(sum(failures.event_cap_failure_n) == 2100);
    assert(sum(failures.stagnation_failure_n) == 9);
    assert(sum(failures.unrecovered_output_n) == 46);
    assert(sum(failures.other_failure_n) == 0);
    cv = campaigns(campaigns.mission == "CV", :);
    nonCv = campaigns(campaigns.mission ~= "CV", :);
    assert(all(cv.successful_exact_event_n == cv.successful_n));
    assert(all(nonCv.successful_exact_event_n == 0));
    fprintf('Validation: %d campaigns, %d grid/robot summaries, %d attempts, %d failures.\n', ...
        height(campaigns), height(groups), sum(campaigns.attempted_n), sum(campaigns.failed_n));
end

function value = adaptiveCap(gridSize, robotCount)
    value = max(5000, ceil(10000 * gridSize^2 * robotCount / (19^2 * 4)));
end

function [m, med, p95, mx] = distributionStats(x)
    x = x(isfinite(x));
    if isempty(x)
        m = nan; med = nan; p95 = nan; mx = nan; return;
    end
    m = mean(x); med = median(x); p95 = prctile(x, 95); mx = max(x);
end

function out = extractDiagnosticEvents(messages)
    out = nan(numel(messages), 1);
    for i = 1:numel(messages)
        token = regexp(char(messages(i)), '"events_processed"\s*:\s*(\d+)', 'tokens', 'once');
        if ~isempty(token), out(i) = str2double(token{1}); end
    end
end

function y = safeRatio(a, b)
    n = min(numel(a), numel(b)); a = a(1:n); b = b(1:n);
    y = nan(size(a)); valid = isfinite(a) & isfinite(b) & b > 0;
    y(valid) = a(valid) ./ b(valid);
end

function y = ratio(a, b)
    if isfinite(a) && isfinite(b) && b ~= 0, y = a / b; else, y = nan; end
end

function value = finiteMin(x)
    x = x(isfinite(x)); if isempty(x), value = nan; else, value = min(x); end
end

function value = finiteMax(x)
    x = x(isfinite(x)); if isempty(x), value = nan; else, value = max(x); end
end

function x = asDouble(x)
    if isnumeric(x) || islogical(x), x = double(x); else, x = str2double(string(x)); end
end

function text = proxyLabel(mission, eventN)
    if eventN > 0
        text = "exact successful scheduler-event counts available";
    else
        text = "cap/step is an upper-bound proxy; successful event counts were not exported";
    end
    if string(mission) == "CV" && eventN == 0
        text = "CV event column unavailable in this file";
    end
end

function text = rangeText(lo, hi)
    if ~isfinite(lo), text = 'not recorded';
    elseif lo == hi, text = sprintf('%.0f', lo);
    else, text = sprintf('%.0f--%.0f', lo, hi);
    end
end

function text = numberOrNA(value, format)
    if isfinite(value), text = sprintf(format, value); else, text = 'not exported'; end
end

function text = multipleOrNA(value)
    if isfinite(value), text = sprintf('%.2fx', value); else, text = 'not available'; end
end
